import 'package:flutter/material.dart';

class ArchiveLanguageScope extends InheritedWidget {
  const ArchiveLanguageScope({
    super.key,
    required this.onChange,
    this.editionLabel = '浏览器本地版',
    required super.child,
  });
  final VoidCallback onChange;
  final String editionLabel;
  static ArchiveLanguageScope? of(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<ArchiveLanguageScope>();
  @override
  bool updateShouldNotify(ArchiveLanguageScope oldWidget) =>
      onChange != oldWidget.onChange || editionLabel != oldWidget.editionLabel;
}

class ArchiveLanguageSwitch extends StatelessWidget {
  const ArchiveLanguageSwitch({super.key});
  @override
  Widget build(BuildContext context) {
    final scope = ArchiveLanguageScope.of(context);
    if (scope == null) return const SizedBox.shrink();
    return TextButton.icon(
      key: const Key('language-switch'),
      onPressed: scope.onChange,
      icon: const Icon(Icons.translate, size: 18),
      label: Text(context.english ? '中文' : 'English'),
    );
  }
}

class ArchiveLanguageBar extends StatelessWidget {
  const ArchiveLanguageBar({super.key, this.isDemo = false});
  final bool isDemo;
  @override
  Widget build(BuildContext context) => ArchiveLanguageScope.of(context) == null
      ? const SizedBox.shrink()
      : Material(
          color: const Color(0xffe7f0eb),
          child: Padding(
            padding: const EdgeInsets.symmetric(horizontal: 16),
            child: Row(
              children: [
                Expanded(
                  child: Text(
                    context.t(
                      isDemo
                          ? '合成示例 · 不保存'
                          : ArchiveLanguageScope.of(context)!.editionLabel,
                    ),
                    style: Theme.of(context).textTheme.bodySmall,
                  ),
                ),
                const ArchiveLanguageSwitch(),
              ],
            ),
          ),
        );
}

extension ArchiveLanguage on BuildContext {
  bool get english => Localizations.localeOf(this).languageCode == 'en';

  String syncStatusText(String source) {
    final conflict = _conflictStatus.firstMatch(source);
    if (conflict != null) {
      return t('有 {count} 项版本冲突', {'count': conflict[1]});
    }
    const suffix = ' · 原始密文已保留';
    if (source.endsWith(suffix)) {
      return '${t(source.substring(0, source.length - suffix.length))} · ${t('原始密文已保留')}';
    }
    return t(source);
  }

  // Call only for interface copy, never for a user's saved text or tags.
  String t(String source, [Map<String, Object?> values = const {}]) {
    final result = english ? englishUi[source] ?? source : source;
    return result.replaceAllMapped(
      _slots,
      (match) =>
          values.containsKey(match[1]) ? '${values[match[1]]}' : match[0]!,
    );
  }
}

final _slots = RegExp(r'\{(\w+)\}');
final _conflictStatus = RegExp(r'^有 (\d+) 项版本冲突$');

